# Verthys Dev Launcher
# Clean residual processes, verify dependencies, then start Tauri dev mode
# Usage: .\dev.ps1

$ErrorActionPreference = "SilentlyContinue"
$projectDir = Join-Path $PSScriptRoot "verthys-tauri"
$srcTauriDir = Join-Path $projectDir "src-tauri"
$nodeModulesDir = Join-Path $projectDir "node_modules"
$kbTypesPatchDir = Join-Path $projectDir "keyboard-types-patched"
$buildErrLog = Join-Path $projectDir "build_err.log"

# Core binary paths — dev runtime consumes a test-hooks Release build:
#   verthys.dll      -> resolved via the build-artifact contract
#                       (build/core/verthys.artifacts.json, generated by the
#                       CMake POST_BUILD step; removes per-generator path guess)
#   resolve_worker_path -> verthys-worker/target/{release,debug}/verthys-worker.exe (release preferred)
#
# P2 机器级安全服务是生产强制依赖。开发机不安装 SYSTEM 服务时，开发启动器
# 使用测试钩子构建并通过 VERTHYS_TEST_MACHINE_LIMITER_BYPASS 仅为本进程树
# 启用机器预算旁路；生产构建（VERTHYS_TEST_HOOKS=OFF）不包含该分支。
. (Join-Path $PSScriptRoot "scripts\lib\artifacts.ps1")
$coreDllPath = $null
try {
    $coreDllPath = Get-VerthysArtifactDll
} catch {
    # Not built yet: leave null; the pre-flight below delegates to
    # build_production.ps1 which builds the core and regenerates the contract.
    $coreDllPath = $null
}
$workerDir        = Join-Path $projectDir "verthys-worker"
$workerReleaseExe = Join-Path $workerDir "target\release\verthys-worker.exe"
$workerDebugExe   = Join-Path $workerDir "target\debug\verthys-worker.exe"
$coreReleaseScript = Join-Path $PSScriptRoot "scripts\build\build_core.release.ps1"

$processNames = @("Verthys", "verthys-worker", "verthys-tauri")

Write-Host ""
Write-Host "========================================" -ForegroundColor Cyan
Write-Host "  Verthys Dev Launcher" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan
Write-Host ""

# Step 0: Load MSVC build environment (root-cause fix for vswhom LNK2019)
# 根因：build_dev.ps1 原未加载 MSVC 环境 → cl.exe 不在 PATH → cc crate 无法编译
# vswhom-sys 的 vswhom.cpp（C++ 源） → 链接时 LNK2019:
# vswhom_find_visual_studio_and_windows_sdk 未解析。
#
# 探测顺序（与 build_production.ps1 一致）：
#   1. 外部已注入 MSVC 工具链环境（VCToolsInstallDir + INCLUDE + LIB +
#      PATH 中的 cl.exe 就绪）→ 直接沿用；
#   2. 否则 dot-source env.load.ps1（本地 VS 安装 + 4 个自定义环境变量，
#      同时设置 INCLUDE/LIB/PATH 与 CC/CXX，覆盖 cc crate 的 MSVC 自动探测）。
Write-Host "[0/5] Loading MSVC build environment..." -ForegroundColor Yellow
if (-not [string]::IsNullOrEmpty($env:VCToolsInstallDir) -and
    -not [string]::IsNullOrEmpty($env:INCLUDE) -and
    -not [string]::IsNullOrEmpty($env:LIB) -and
    (Get-Command cl.exe -ErrorAction SilentlyContinue)) {
    Write-Host "  检测到已注入的 MSVC 工具链环境，直接沿用" -ForegroundColor Green
} else {
    $envLoadScript = Join-Path $PSScriptRoot "scripts\lib\env.load.ps1"
    if (-not (Test-Path $envLoadScript)) {
        Write-Host "  !! env.load.ps1 not found: $envLoadScript" -ForegroundColor Red
        Write-Host "     vswhom-sys 将因 cl.exe 缺失而链接失败（LNK2019）" -ForegroundColor Red
        exit 1
    }
    # env.load.ps1 内部设置 EAP=Stop + Set-StrictMode -Version 3.0，dot-source 会污染当前
    # 作用域。保存本脚本 EAP（SilentlyContinue），加载后恢复；StrictMode 重置为 Off
    # （本脚本原无严格模式，避免后续 Get-Process/Get-NetTCPConnection 等误报未定义变量）。
    $prevEAP = $ErrorActionPreference
    . $envLoadScript
    $ErrorActionPreference = $prevEAP
    Set-StrictMode -Off
}
# 校验 cl.exe 确实可用（两条路径最终都必须让 cl.exe 进入 PATH）
$clCheck = Get-Command cl.exe -ErrorAction SilentlyContinue
if ($clCheck) {
    Write-Host "  cl.exe available: $($clCheck.Source)" -ForegroundColor Green
} else {
    Write-Host "  !! cl.exe still not in PATH" -ForegroundColor Red
    Write-Host "     vswhom-sys LNK2019 将复发" -ForegroundColor Red
    exit 1
}

# Step 1: Clean residual processes
Write-Host "[1/5] Checking residual processes..." -ForegroundColor Yellow

$killed = 0
foreach ($procName in $processNames) {
    $procs = Get-Process -Name $procName -ErrorAction SilentlyContinue
    if ($procs) {
        foreach ($p in $procs) {
            try {
                Write-Host "  -> Killing $($p.ProcessName) (PID: $($p.Id))" -ForegroundColor DarkYellow
                Stop-Process -Id $p.Id -Force -ErrorAction Stop
                $killed++
            } catch {
                Write-Host "  !! Cannot kill $($p.ProcessName) (PID: $($p.Id)): $_" -ForegroundColor Red
            }
        }
    }
}

if ($killed -eq 0) {
    Write-Host "  No residual processes" -ForegroundColor Green
} else {
    Write-Host "  Cleaned $killed residual processes" -ForegroundColor Green
    Start-Sleep -Milliseconds 500
}

# Step 2: Check port 1420
Write-Host ""
Write-Host "[2/5] Checking port 1420..." -ForegroundColor Yellow

$portConn = Get-NetTCPConnection -LocalPort 1420 -State Listen -ErrorAction SilentlyContinue
if ($portConn) {
    $portPid = $portConn.OwningProcess | Select-Object -First 1
    if ($portPid) {
        $portProc = Get-Process -Id $portPid -ErrorAction SilentlyContinue
        if ($portProc) {
            try {
                Write-Host "  -> Port 1420 occupied by $($portProc.ProcessName) (PID: $portPid), releasing..." -ForegroundColor DarkYellow
                Stop-Process -Id $portPid -Force -ErrorAction Stop
                Write-Host "  Port released" -ForegroundColor Green
                Start-Sleep -Milliseconds 500
            } catch {
                Write-Host "  !! Cannot release port: $_" -ForegroundColor Red
            }
        }
    }
} else {
    Write-Host "  Port 1420 is free" -ForegroundColor Green
}

# Step 3: Verify dependencies
Write-Host ""
Write-Host "[3/5] Verifying dependencies..." -ForegroundColor Yellow

# 3.1 Clean stale build error log
if (Test-Path $buildErrLog) {
    Remove-Item $buildErrLog -Force
    Write-Host "  -> Cleaned stale build_err.log" -ForegroundColor DarkYellow
}

# 3.2 Check node_modules（缺失时 npm ci，以 package-lock.json 为唯一事实源）
if (-not (Test-Path $nodeModulesDir)) {
    Write-Host "  -> node_modules missing, running npm ci..." -ForegroundColor DarkYellow
    Set-Location $projectDir
    & npm ci 2>&1 | ForEach-Object { Write-Host "    $_" -ForegroundColor Gray }
    if ($LASTEXITCODE -ne 0) {
        Write-Host "  !! npm ci failed" -ForegroundColor Red
        exit 1
    }
    Write-Host "  Dependencies installed" -ForegroundColor Green
} else {
    Write-Host "  node_modules OK" -ForegroundColor Green
}

# 3.3 Check keyboard-types patch
if (-not (Test-Path $kbTypesPatchDir)) {
    Write-Host "  !! keyboard-types-patched directory missing: $kbTypesPatchDir" -ForegroundColor Red
    Write-Host "     Cargo.toml [patch.crates-io] requires this directory" -ForegroundColor Red
    exit 1
}
$kbPatchCargo = Join-Path $kbTypesPatchDir "Cargo.toml"
$kbPatchModRs = Join-Path $kbTypesPatchDir "src\modifiers.rs"
if (-not (Test-Path $kbPatchCargo) -or -not (Test-Path $kbPatchModRs)) {
    Write-Host "  !! keyboard-types-patched incomplete (missing Cargo.toml or src/modifiers.rs)" -ForegroundColor Red
    exit 1
}
Write-Host "  keyboard-types patch OK" -ForegroundColor Green

# 3.4 Ensure Cargo.lock patch is applied（只读断言，不写锁文件）
# [patch.crates-io] 生效标志：keyboard-types 条目无 source 字段（本地 path
# 补丁无注册表来源）。不执行 cargo update（会改写锁文件）。
$kbLockPath = Join-Path $srcTauriDir "Cargo.lock"
$kbLockContent = Get-Content $kbLockPath -Raw
$kbPatchBlock = [regex]::Match($kbLockContent,
    '\[\[package\]\](?:(?!\[\[).)*?name = "keyboard-types".*?(?=(\r?\n\[\[package\]\])|$)',
    [System.Text.RegularExpressions.RegexOptions]::Singleline)
$patchConfirmed = $kbPatchBlock.Success -and $kbPatchBlock.Value -notmatch '(?m)^source\s*='
if (-not $patchConfirmed) {
    Write-Host "  !! keyboard-types patch not applied in Cargo.lock" -ForegroundColor Red
    exit 1
}
Write-Host "  Cargo.lock patch confirmed" -ForegroundColor Green

# Step 4: Pre-flight core binaries (verthys.dll + verthys-worker.exe)
# verthys.dll location comes from the build-artifact contract (read above);
# verthys-worker is resolved via path_resolver.rs (release preferred).
#
# 开发模式必须使用测试钩子 core：生产 DLL 在 P2 服务未安装时会 fail-closed，
# 而开发机通常没有安装 SYSTEM 服务。这里检测 DLL 是否包含测试旁路标记；
# 不含则重建为测试钩子构建，并同步重建 worker（worker 固化 DLL 全文件哈希）。
Write-Host ""
Write-Host "[4/5] Pre-flight: core binaries (verthys.dll + verthys-worker.exe)..." -ForegroundColor Yellow

$dllMissing    = ($null -eq $coreDllPath) -or -not (Test-Path $coreDllPath)
$workerMissing = -not (Test-Path $workerReleaseExe) -and -not (Test-Path $workerDebugExe)

$needsTestHooksCore = $false
# Tauri resources 在 cargo build 时校验文件存在：P2 服务载荷（服务 exe + 根证书）
# 必须已同步到 src-tauri\service-payload。生产构建脚本会刷新它们；
# 首次开发可先从 build\security-service 复制，缺失则提示先跑一次服务构建。
$serviceResourceDir = Join-Path $projectDir "verthys-tauri\src-tauri\service-payload"
$legacyServiceResourceDir = Join-Path $projectDir "verthys-tauri\src-tauri\security-service"
if (Test-Path -LiteralPath $legacyServiceResourceDir) {
    Remove-Item -LiteralPath $legacyServiceResourceDir -Recurse -Force -ErrorAction SilentlyContinue
}
$serviceSourceDir = Join-Path $projectDir "build\security-service"
foreach ($name in @("VerthysSecuritySvc.exe", "VerthysRootCA.cer")) {
    $target = Join-Path $serviceResourceDir $name
    if (-not (Test-Path -LiteralPath $target)) {
        $source = Join-Path $serviceSourceDir $name
        if (Test-Path -LiteralPath $source) {
            New-Item -ItemType Directory -Path $serviceResourceDir -Force | Out-Null
            Copy-Item -LiteralPath $source -Destination $target -Force
            Write-Host ("  -> 已同步 P2 服务资源: {0}" -f $name) -ForegroundColor DarkYellow
        } else {
            Write-Host ("  !! 缺少 P2 服务资源 {0}；请先运行 build_production.ps1 -Profile local -AllowLocal -SkipTauri 一次" -f $name) -ForegroundColor Red
            exit 1
        }
    }
}

if (-not $dllMissing) {
    $info = Get-Item $coreDllPath
    Write-Host ("  verthys.dll OK ({0}, {1} KB)" -f $info.LastWriteTime, [math]::Round($info.Length / 1KB, 1)) -ForegroundColor Green
    # 带发布签名的 DLL 在运行期要求宿主同证书签名；dev 宿主未签名会被拒绝。
    # 这里只提示恢复路径，不擅自重建用户已验证的产物。
    $devSig = Get-AuthenticodeSignature -LiteralPath $coreDllPath
    if ($null -ne $devSig.SignerCertificate) {
        Write-Host "  !! verthys.dll 带发布者 Authenticode 签名：dev 宿主未签名会被调用方认证拒绝；" -ForegroundColor Yellow
        Write-Host "     请在不注入签名证书的环境重跑 build_production.ps1 -Profile local -SkipTauri 恢复未签名开发 DLL" -ForegroundColor Yellow
    }
    try {
        $dllAscii = [Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($coreDllPath))
        $needsTestHooksCore = -not $dllAscii.Contains("VERTHYS_TEST_MACHINE_LIMITER_BYPASS")
    } catch {
        Write-Host "  !! 读取 verthys.dll 失败: $_" -ForegroundColor Red
        exit 1
    }
    if ($needsTestHooksCore) {
        Write-Host "  -> verthys.dll 为生产构建（不含开发旁路），将重建为测试钩子构建" -ForegroundColor DarkYellow
    }
} else {
    Write-Host "  -> verthys.dll missing (no build-artifact contract or DLL cleared)" -ForegroundColor DarkYellow
}

if (-not $workerMissing) {
    $wPath = if (Test-Path $workerReleaseExe) { $workerReleaseExe } else { $workerDebugExe }
    $info = Get-Item $wPath
    Write-Host ("  verthys-worker.exe OK ({0}, {1} KB)" -f $info.LastWriteTime, [math]::Round($info.Length / 1KB, 1)) -ForegroundColor Green
} else {
    Write-Host "  -> verthys-worker.exe missing (both release and debug)" -ForegroundColor DarkYellow
}

if ($dllMissing -or $workerMissing -or $needsTestHooksCore) {
    $coreBuilt = $false
    if ($dllMissing -or $needsTestHooksCore) {
        if (-not (Test-Path $coreReleaseScript)) {
            Write-Host "  !! build_core.release.ps1 not found: $coreReleaseScript" -ForegroundColor Red
            exit 1
        }
        Write-Host "  -> 重建 core（测试钩子，Release）..." -ForegroundColor DarkYellow
        & $coreReleaseScript -TestHooks -NoPause
        if ($LASTEXITCODE -ne 0) {
            Write-Host "  !! build_core.release.ps1 -TestHooks failed (exit=$LASTEXITCODE)" -ForegroundColor Red
            exit 1
        }
        try {
            $coreDllPath = Get-VerthysArtifactDll
        } catch {
            Write-Host "  !! verthys.dll still missing after build: $_" -ForegroundColor Red
            exit 1
        }
        $coreBuilt = $true
    }

    # worker 固化 verthys.dll 全文件哈希；DLL 重建后必须同步重建 worker。
    if ($workerMissing -or $coreBuilt) {
        if (-not (Test-Path $workerDir)) {
            Write-Host "  !! worker 目录缺失: $workerDir" -ForegroundColor Red
            exit 1
        }
        Write-Host "  -> 重建 worker（同步 verthys.dll 哈希基线）..." -ForegroundColor DarkYellow
        Push-Location $workerDir
        try {
            & cargo build --release
            $workerBuildExit = $LASTEXITCODE
        } finally {
            Pop-Location
        }
        if ($workerBuildExit -ne 0) {
            Write-Host "  !! cargo build --release failed (exit=$workerBuildExit)" -ForegroundColor Red
            exit 1
        }
    }

    if (-not (Test-Path $workerReleaseExe) -and -not (Test-Path $workerDebugExe)) {
        Write-Host "  !! verthys-worker.exe still missing after build" -ForegroundColor Red
        exit 1
    }
    Write-Host "  Core binaries built and verified (test hooks)" -ForegroundColor Green
} else {
    Write-Host "  Core binaries ready (test hooks, no rebuild needed)" -ForegroundColor Green
}

# Step 5: Start dev mode
Write-Host ""
Write-Host "[5/5] Starting Tauri dev mode..." -ForegroundColor Yellow
Write-Host "  Dir: $projectDir" -ForegroundColor DarkGray
# 仅开发进程树：P2 服务未安装时跳过机器预算调用；生产构建不编译该分支。
$env:VERTHYS_TEST_MACHINE_LIMITER_BYPASS = "1"
Write-Host "  [dev] P2 机器预算测试旁路已启用（仅本开发进程树；生产构建仍 fail-closed）" -ForegroundColor Yellow
Write-Host ""

Set-Location $projectDir
npx tauri dev
