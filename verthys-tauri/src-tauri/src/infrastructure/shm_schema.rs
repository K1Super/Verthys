/*
 * @file infrastructure/shm_schema.rs
 * @brief SHM 协议契约主进程侧入口 - 通过 include! 引入共享定义确保主/子进程数据结构同源
 *
 * =============================================================================
 * 设计意图
 * =============================================================================
 * 主进程与 verthys-worker 子进程均使用 Rust 实现，共享内存通信所需的数据结构
 * 必须保持严格的内存布局一致性。本模块通过 `include!()` 宏直接引入位于
 * 项目根目录的共享源文件（`shm_schema.rs`），使两端在同一份源代码上编译，
 * 根除手动同步导致的版本分化风险。
 *
 * =============================================================================
 * 编译期校验
 * =============================================================================
 * 共享源文件尾部包含多个 `const_assert_eq!` 静态断言，在编译时验证结构体
 * 大小、字段偏移与常量定义的一致性。若任何定义被修改但未同步更新常量，
 * 编译将直接失败，强制开发者对齐两端协议。
 *
 * =============================================================================
 * 使用约束
 * =============================================================================
 * 1. 本文件仅作为 include! 的载体，不定义任何业务逻辑或额外结构体。
 * 2. 严禁在此文件中覆盖或重新定义共享源内的任何常量、结构体或函数，
 *    以免遮蔽同源定义，破坏一致性保障。
 * 3. 共享源文件中部分定义仅为 worker 端所需，主进程侧虽不引用但允许
 *    存在（已通过 `#![allow(dead_code)]` 抑制警告）。
 *
 * =============================================================================
 * 维护说明
 * =============================================================================
 * - 修改共享内存协议时，仅需编辑项目根目录下的 `shm_schema.rs` 文件，
 *   本文件及 worker 侧的对应入口均无需单独修改。
 * - 确保 `include!` 路径正确指向共享源文件（当前为 `../../../shm_schema.rs`，
 *   相对于本文件所在目录）。
 */

// 共享源中包含仅 worker 端使用的定义，主进程侧不直接引用，此处统一抑制未使用警告。
// 注意：不能在共享源文件内使用 #![allow(dead_code)] 因为 include! 展开后不是 crate 根。
#![allow(dead_code)]

// 引入共享 SHM 协议契约（路径：verthys-tauri/shm_schema.rs）
include!("../../../shm_schema.rs");