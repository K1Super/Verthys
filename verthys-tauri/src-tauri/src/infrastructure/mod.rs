/*
 * @file infrastructure/mod.rs
 * @brief 基础设施层模块聚合入口
 *
 * 本模块集中封装操作系统交互、进程管理、安全加固、路径解析、资源共享等底层能力，
 * 供上层业务模块（服务层、控制器层）调用，所有实现均遵循架构安全规范。
 *
 * =============================================================================
 * 设计原则
 * =============================================================================
 * - 分层隔离：基础设施层不依赖任何业务模块，确保业务逻辑与平台细节解耦。
 * - 安全优先：所有涉及句柄、密钥、共享内存等敏感操作，必须强制遵循安全规范
 *   （如禁止句柄继承、敏感内存自动清零、常量时间比较等），并纳入CI门禁检查。
 * - 高效可靠：日志管道采用异步非阻塞设计，共享内存只读映射减少锁竞争，关键路径
 *   避免不必要的计算和IO，确保业务线程无感。
 *
 * =============================================================================
 * 模块清单
 * =============================================================================
 * - log_pipe          ：异步结构化日志管道（后台消费线程 + 分级投递 + 文件降级）
 * - process_guard     ：多进程资源隔离，阻止子进程意外继承父进程句柄
 * - handle_factory    ：Windows内核对象句柄统一工厂，强制 bInheritHandle=FALSE
 * - shared_memory     ：跨进程共享内存只读映射与记录解析
 * - device_fingerprint：生成设备唯一机器码（基于硬件信息经SHA-256哈希）
 * - path_resolver     ：解析关键可执行文件/DLL路径，并提供完整性校验
 * - resource_guard    ：校验前端资源目录完整性（SHA-256）
 * - shm_schema        ：通过include!引入SHM协议契约，确保主/子进程数据结构同源
 * - app_paths         ：解析应用数据目录（使用SHGetKnownFolderPath，支持便携模式与长路径）
 * - console_handler   ：注册Windows控制台信号处理器，转换为CancellationToken触发优雅退出
 *
 * =============================================================================
 * 使用规范
 * =============================================================================
 * - 日志发送端（LogSender）不得设计为全局静态变量，必须通过依赖注入（如Context）传递。
 * - 所有句柄创建必须通过 handle_factory，禁止直接调用Win32 API创建句柄。
 * - 共享内存映射在进程启动时建立，退出前需显式卸载，避免资源泄漏。
 * - 设备指纹应在首次启动时生成并缓存，避免频繁读取硬件信息。
 *
 * =============================================================================
 * 安全红线（CI门禁强制）
 * =============================================================================
 * 1. 所有句柄必须通过 handle_factory 创建，确保不可继承属性。
 * 2. 敏感数据（会话密钥、密码等）必须使用 Zeroizing 包装，确保内存自动清零。
 * 3. 所有加密比较（HMAC、Nonce）必须使用常量时间比较函数。
 * 4. 共享内存映射必须为只读，防止被非法篡改。
 * 5. 日志输出不得包含任何敏感信息（密钥、密码、令牌等）。
 *
 * =============================================================================
 * 依赖与兼容性
 * =============================================================================
 * - 外部依赖：windows-rs, crossbeam-channel, serde, chrono, zeroize, sha2 等。
 * - 内部依赖：各模块间保持单向依赖，避免循环。
 * - 平台支持：Windows 为一级目标，非Windows平台提供条件编译存根确保编译通过。
 */
pub mod log_pipe;
pub mod process_guard;
pub mod handle_factory;
pub mod shared_memory;
pub mod device_fingerprint;
pub mod path_resolver;
pub mod resource_guard;
/// SHM 协议契约（通过 include! 引入共享源文件，保证主/子进程数据结构一致）
pub mod shm_schema;
/// 应用数据目录解析（使用 SHGetKnownFolderPath，支持便携模式与长路径）
pub mod app_paths;
/// Windows 控制台信号处理（SetConsoleCtrlHandler → CancellationToken）
pub mod console_handler;