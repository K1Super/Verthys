/*
 * @file constants/record_types.ts
 * @brief Verthys 记录类型统一分配表（单一真相源）
 *
 * 本文件定义 Verthys 加密库中所有记录类型的常量，作为前端与后端（C 层）
 * 共享的类型标识符。所有记录类型值必须全局唯一，并按功能分区分配，
 * 以根治历史遗留的类型冲突问题（如 TYPE_GLOBAL_KEY 与 TYPE_ACCOUNT 值重叠）。
 *
 * =============================================================================
 * 设计原则
 * =============================================================================
 * 1. 单一真相源：所有记录类型常量仅在此处定义，禁止在 .vue 或其他 .ts 中
 *    自行定义数值，确保前后端类型值的一致性。
 * 2. 全局唯一性：每个常量值在整个枚举空间中唯一，避免误识别。
 * 3. 与 C 层对齐：常量值须与 `verthys.h` 中的 `VerthysRecordType` 枚举保持
 *    一致，任何变更须同步修改两端。
 * 4. 分区隔离：按业务模块划分值域（业务数据 0x01-0x07，安全密钥 0x10-0x1F，
 *    迁移专用 0x20-0x2F），降低未来冲突风险。
 *
 * =============================================================================
 * 历史问题与根治策略
 * =============================================================================
 * 原始缺陷：
 *   - TYPE_GLOBAL_KEY (0x10) 与 TYPE_ACCOUNT (0x10) 值相同 → 全局密钥记录与
 *     账户记录互相误识，导致“设置遗忘/密钥验证无效/增删改异常/删除后复活”
 *     等致命故障。
 *   - TYPE_PHOTO_CHUNK (0x05) 与 TYPE_FILEVERTHYS_META (0x05) 值相同 → 照片
 *     数据块与文件保险箱元数据互相误识。
 *   - background-tasks.ts 中硬编码的 TYPE_PRIORITY 使用 C 层规范值，与前端
 *     实际存储类型不匹配，导致预加载失效。
 *
 * 根治措施：
 *   - 重新分配冲突类型值，并保留旧值常量供迁移识别。
 *   - TYPE_PRIORITY 改为引用本文件定义，消除硬编码。
 *   - 迁移逻辑通过内容嗅探区分新旧值，确保升级过程平滑。
 *
 * =============================================================================
 * 值域分配规则
 * =============================================================================
 *   - 0x01-0x07：模块业务数据（照片、账户、证书、文件保险箱及其子类型）
 *   - 0x08-0x0F：预留扩展
 *   - 0x10-0x1F：安全/密钥管理记录（全局密钥、模块密钥等）
 *   - 0x20-0x2F：旧格式迁移记录（仅用于读取，不再新建）
 *
 * =============================================================================
 * 使用约束
 * =============================================================================
 * - 新增类型时，必须先检查本表，确保不与现有值重复。
 * - 修改已有类型值须同时更新 C 层头文件及迁移逻辑，否则将导致数据损坏。
 * - 迁移用常量（如 TYPE_ACCOUNT_OLD）仅在迁移模块中引用，禁止用于新建记录。
 *
 * =============================================================================
 * 维护说明
 * =============================================================================
 * - 任何类型值的变更须经过架构评审，并同步更新本注释中的分区说明。
 * - 迁移完成后（旧格式完全弃用），可考虑移除 `_OLD` 常量以简化代码。
 */

/* === 照片模块 === */

/** 照片元数据记录，用于存储照片的缩略图、尺寸、标签等属性。 */
export const TYPE_PHOTO_META = 0x01;

/** 照片原始数据块，用于存储加密后的照片二进制内容。 */
export const TYPE_PHOTO_CHUNK = 0x05;

/* === 账户模块 === */

/**
 * 独立账户记录（每条账户对应一条 verthys 记录）。
 * 原值 0x10 与全局密钥冲突，现修正为 0x02（与 C 层 VERTHYS_RECORD_ACCOUNT 对齐）。
 * 迁移时需将旧值 0x10 的账户记录转换为新值。
 */
export const TYPE_ACCOUNT = 0x02;

/**
 * 旧版账户列表记录（仅用于迁移读取，不再新建）。
 * 该类型在 v1 格式中用于存储所有账户的汇总列表，现已被独立记录模式取代。
 */
export const TYPE_ACCOUNT_LIST = 0x20;

/**
 * 更旧版单条账户记录（仅用于迁移读取）。
 * 存在于极早期版本，需通过内容嗅探识别并转换为新格式。
 */
export const TYPE_ACCOUNT_LEGACY = 0x03;

/* === 证书模块 === */

/** 独立证书记录（每条证书一条 verthys 记录），用于存储 X.509 证书信息。 */
export const TYPE_CERT = 0x11;

/** 旧版证书列表记录（仅用于迁移读取）。 */
export const TYPE_CERT_LIST = 0x21;

/** 更旧版单条证书记录（仅用于迁移读取）。 */
export const TYPE_CERT_LEGACY = 0x06;

/* === 文件保险箱模块 === */

/**
 * 文件保险箱元数据记录，描述加密文件的属性（大小、分块信息等）。
 * 原值 0x05 与 TYPE_PHOTO_CHUNK 冲突，现修正为 0x08。
 * 迁移时需将旧值 0x05 的元数据记录转换为新值。
 */
export const TYPE_FILEVERTHYS_META = 0x08;

/**
 * 文件保险箱数据块记录，存储加密文件的分片数据。
 * 值保持 0x04 不变（原 TYPE_CHUNK 重命名）。
 */
export const TYPE_FILEVERTHYS_CHUNK = 0x04;

/* === 安全/密钥管理 === */

/** 全局主密钥记录，存储加密后的主密钥及其派生参数。 */
export const TYPE_GLOBAL_KEY = 0x10;

/** 模块独立密钥记录，用于特定模块（如子密钥）的加密。 */
export const TYPE_MODULE_KEY = 0x12;

/**
 * 模块密钥保护开关配置记录，存储每个模块的密钥保护策略（如是否启用双因素）。
 */
export const TYPE_MODULE_KEY_CONFIG = 0x13;

/* === 迁移辅助：旧值映射（仅用于迁移识别，不可用于新建） === */

/**
 * 旧版账户类型值（已废弃）。
 * 迁移逻辑通过检查记录内容区分旧账户与全局密钥。
 */
export const TYPE_ACCOUNT_OLD = 0x10;

/**
 * 旧版文件保险箱元数据类型值（已废弃）。
 * 迁移逻辑通过内容嗅探区分旧元数据与照片块。
 */
export const TYPE_FILEVERTHYS_META_OLD = 0x05;

/* === 渲染优先级（用于后台预加载） === */

/**
 * 列表渲染优先级数组，按用户点击概率从高到低排序。
 * 该数组用于后台预加载策略，优化用户体验。
 * 取值引用本文件常量，避免与硬编码值脱节。
 */
export const TYPE_PRIORITY = [
  TYPE_PHOTO_META,       // 照片
  TYPE_ACCOUNT,          // 账户
  TYPE_FILEVERTHYS_META,   // 文件保险箱元数据
  TYPE_CERT,             // 证书
] as const;